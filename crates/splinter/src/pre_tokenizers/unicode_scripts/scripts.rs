/// The script id of `c`.
pub(crate) fn get_script(c: char) -> u8 {
    let cp = c as u32;
    match RANGES.binary_search_by(|&(lo, hi, _)| {
        if hi < cp {
            std::cmp::Ordering::Less
        } else if lo > cp {
            std::cmp::Ordering::Greater
        } else {
            std::cmp::Ordering::Equal
        }
    }) {
        Ok(i) => RANGES[i].2,
        Err(_) => ANY,
    }
}
